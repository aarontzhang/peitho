// Peitho Eval — Prompt Templates
// Three types: persona-informed ad generation, baseline (ChatGPT-style),
// and blind evaluation.

export function buildInformedPrompt(persona, campaign) {
  const isCodePersona = ["code-first", "peer-validated", "tutorial-first"].includes(
    persona.cognition.informationProcessing
  );

  return `You are a B2B advertising strategist specializing in ${campaign.company}.
Generate a LinkedIn Sponsored Content ad (1080x1080 image + text).

## Brand
${campaign.product}
Company: ${campaign.company}
Competitors: ${campaign.competitors.join(", ")}
Challenge: ${campaign.currentPain}

## Target Persona
Role: ${persona.role} (${persona.segment})
Company stage: ${persona.companyStage}

### Psychology
- Info processing: ${persona.cognition.informationProcessing}
- Proof hierarchy: ${persona.cognition.proofHierarchy.join(" > ")}
- Risk orientation: ${persona.cognition.riskOrientation}

### Objections
Surface: ${persona.objections.surface.join("; ")}
Real: ${persona.objections.real.join("; ")}

### Anti-patterns (DO NOT do these)
${persona.antiPatterns.map((a) => `- ${a}`).join("\n")}

### Communication
- Format: ${persona.communication.preferredFormat}
- Social proof: ${persona.communication.socialProofType}
- Attention: ${persona.communication.attentionWindow}

Output valid JSON only. Schema:
{
  "headline": string (bold text for the image — max 8 words),
  "bodyText": string (LinkedIn text above image, max 150 chars),
  "linkedinHeadline": string (text below image, max 70 chars),
  "cta": string (button text),
  "tone": string,
  "persuasionAngle": string (the psychological lever),
  "rationale": string (why this works for THIS specific persona)
}`;
}

export function buildBaselinePrompt(campaign, personaRole) {
  // This simulates what someone would type into ChatGPT/Gemini
  return `Write a LinkedIn ad for ${campaign.product}.

Target audience: ${personaRole}
Company: ${campaign.company}

The ad should have an image (1080x1080) with a headline, plus LinkedIn text above and below the image.

Output valid JSON only. Schema:
{
  "headline": string (bold text for the image — max 8 words),
  "bodyText": string (LinkedIn text above image, max 150 chars),
  "linkedinHeadline": string (text below image, max 70 chars),
  "cta": string (button text),
  "tone": string,
  "persuasionAngle": string (the approach used),
  "rationale": string (why this approach)
}`;
}

export function buildEvalPrompt(adA, adB, personaRole, personaSegment) {
  return `You are an expert ad evaluator conducting a blind assessment. You don't know which ad was generated by which method.

## Context
These two LinkedIn ads target the same person:
- Role: ${personaRole}
- Segment: ${personaSegment}

## Ad A
- Image headline: "${adA.headline}"
- LinkedIn text: "${adA.bodyText}"
- Below-image headline: "${adA.linkedinHeadline}"
- CTA: "${adA.cta}"
- Tone: "${adA.tone}"

## Ad B
- Image headline: "${adB.headline}"
- LinkedIn text: "${adB.bodyText}"
- Below-image headline: "${adB.linkedinHeadline}"
- CTA: "${adB.cta}"
- Tone: "${adB.tone}"

Score EACH ad on these 5 dimensions (1-10 scale):

1. **Attention** — Would this stop the scroll? Does the headline demand a second look?
2. **Relevance** — Does this feel like it's "for me"? Does it speak to my specific situation?
3. **Emotional Resonance** — Does this make me feel something? Does the angle land authentically?
4. **Clarity** — Do I immediately understand what's offered and why I should care?
5. **CTA Effectiveness** — Am I motivated to take the next step?

Output valid JSON only. Schema:
{
  "adA": {
    "attention": number,
    "relevance": number,
    "resonance": number,
    "clarity": number,
    "ctaEffectiveness": number,
    "composite": number (weighted: attention 25%, relevance 25%, resonance 20%, clarity 15%, cta 15%),
    "strengths": string,
    "weaknesses": string
  },
  "adB": {
    "attention": number,
    "relevance": number,
    "resonance": number,
    "clarity": number,
    "ctaEffectiveness": number,
    "composite": number,
    "strengths": string,
    "weaknesses": string
  },
  "winner": "A" | "B" | "tie",
  "reasoning": string (2-3 sentences on why the winner is better for this specific persona)
}`;
}
